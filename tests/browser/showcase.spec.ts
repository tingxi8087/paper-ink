test('narrow mobile header and gallery links remain reachable at 320px', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 780 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/#/showcase');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
  await expect(page.getByRole('button', { name: '展开导航' })).toHaveCount(0);
  await page.getByRole('button', { name: '搜索组件和文档', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '搜索组件和文档', exact: true });
  await expect(dialog).toHaveCSS('opacity', '1');
  expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(320);
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: '工作室设置组件文档', exact: true }).click();
  await expect(page).toHaveURL(/#\/form$/);
  await page.goto('/#/showcase');
  await page.getByRole('link', { name: '开始使用 Paper Ink', exact: false }).click();
  await expect(page).toHaveURL(/#\/guide$/);
});
